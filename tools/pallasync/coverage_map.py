def annotate(ledger):
    assert len(CHECKLIST) == len(ledger["checklist"]) == 28
    for row, (sections, implementation, tests, remaining) in zip(ledger["checklist"], CHECKLIST):
        row.update(sections=sections, implementation=implementation, tests=tests,
                   remaining=remaining, verification_scope="targeted_partial")
    for row in ledger["interoperability"]:
        row.setdefault("sections", ["Appendix B " + row["id"]])
    for kind, appendix in (("vectors", "C"), ("examples", "D")):
        for row in ledger[kind]:
            row.setdefault("sections", ["Appendix " + appendix + " " + row["id"]])
    return ledger
